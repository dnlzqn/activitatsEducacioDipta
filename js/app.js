// Punt d'entrada
// =====================================================

async function initApp() {

    console.log("Inicialitzant aplicació...");

    // -------------------------------------------------
    // Interfície
    // -------------------------------------------------

    initUI();


    // -------------------------------------------------
    // Mapa
    // -------------------------------------------------

    createMap();


    // -------------------------------------------------
    // Dades
    // -------------------------------------------------

    await loadAllActivities();


    // -------------------------------------------------
    // Crear marcadors
    // -------------------------------------------------

    buildMarkers();


    // -------------------------------------------------
    // Aplicar filtres inicials
    // -------------------------------------------------

    refreshUI();


    console.log(

        `✔ Aplicació inicialitzada (${state.activities.length} activitats)`

    );

}



// =====================================================
// Inici
// =====================================================

document.addEventListener(

    "DOMContentLoaded",

    initApp

);
